-- Complete schema for a fresh wallet database. Monetary values are whole INR paise.
-- Consolidated bootstrap: tables, indexes, seed data, and immutable-history guards.
CREATE TYPE kyc_status AS ENUM ('PENDING', 'VERIFIED', 'REJECTED');
CREATE TYPE account_type AS ENUM ('CASH_IN', 'CASH_OUT', 'FEE_REVENUE', 'INTERNAL_TRANSFER', 'REVERSAL');
CREATE TYPE transaction_type AS ENUM ('TOPUP', 'TRANSFER', 'WITHDRAWAL', 'REVERSAL');
CREATE TYPE transaction_status AS ENUM ('PENDING', 'POSTED', 'FAILED', 'HELD');
CREATE TYPE idempotency_status AS ENUM ('IN_PROGRESS', 'COMPLETED');

CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    kyc_status kyc_status NOT NULL DEFAULT 'PENDING',
    CONSTRAINT users_email_unique UNIQUE (email),
    CONSTRAINT users_email_normalized CHECK (email = lower(btrim(email)))
);

CREATE TABLE wallets (
    wallet_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_name VARCHAR(100) NOT NULL,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    balance BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT wallets_balance_nonnegative CHECK (balance >= 0)
);
CREATE INDEX wallets_user_id_idx ON wallets(user_id);

-- Preserve the original category catalog; it does not hold money balances.
CREATE TABLE accounts (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_type account_type NOT NULL UNIQUE
);
INSERT INTO accounts(account_type)
VALUES ('CASH_IN'), ('CASH_OUT'), ('FEE_REVENUE'), ('INTERNAL_TRANSFER'), ('REVERSAL');

-- These are actual system ledger participants. Their signed balances are derived from entries.
CREATE TABLE system_accounts (
    system_account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_type VARCHAR(32) NOT NULL UNIQUE,
    CONSTRAINT system_accounts_type CHECK (account_type IN ('CASH_IN', 'CASH_OUT', 'FEE_REVENUE'))
);
INSERT INTO system_accounts(account_type) VALUES ('CASH_IN'), ('CASH_OUT'), ('FEE_REVENUE');

CREATE TABLE transactions (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_type transaction_type NOT NULL,
    transaction_status transaction_status NOT NULL DEFAULT 'PENDING',
    transaction_amount_paise BIGINT NOT NULL,
    transaction_date TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    posted_at TIMESTAMPTZ,
    wallet_id BIGINT NOT NULL REFERENCES wallets(wallet_id),
    initiated_by_user_id BIGINT NOT NULL REFERENCES users(user_id),
    account_id BIGINT NOT NULL REFERENCES accounts(account_id),
    reversal_of_transaction_id BIGINT REFERENCES transactions(transaction_id),
    CONSTRAINT transactions_amount_positive CHECK (transaction_amount_paise > 0),
    CONSTRAINT transactions_reversal_type CHECK (
        (transaction_type = 'REVERSAL') = (reversal_of_transaction_id IS NOT NULL)
    ),
    CONSTRAINT transactions_not_self_reversal CHECK (
        reversal_of_transaction_id IS NULL OR reversal_of_transaction_id <> transaction_id
    ),
    CONSTRAINT transactions_posted_time CHECK (
        (transaction_status = 'POSTED') = (posted_at IS NOT NULL)
    )
);
CREATE INDEX transactions_wallet_id_idx ON transactions(wallet_id);
CREATE INDEX transactions_wallet_recent_transfers_idx
    ON transactions(wallet_id, transaction_date DESC, transaction_id DESC)
    WHERE transaction_type = 'TRANSFER';
CREATE INDEX transactions_posted_user_window_idx
    ON transactions(initiated_by_user_id, posted_at)
    WHERE transaction_type = 'TRANSFER' AND transaction_status = 'POSTED';
CREATE UNIQUE INDEX transactions_one_posted_reversal
    ON transactions(reversal_of_transaction_id)
    WHERE reversal_of_transaction_id IS NOT NULL AND transaction_status = 'POSTED';

CREATE INDEX transactions_posted_outgoing_window_idx
    ON transactions(wallet_id, posted_at) INCLUDE (transaction_amount_paise)
    WHERE transaction_type = 'TRANSFER' AND transaction_status = 'POSTED';

CREATE TABLE ledger_entries (
    ledger_entry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT NOT NULL REFERENCES transactions(transaction_id),
    wallet_id BIGINT REFERENCES wallets(wallet_id),
    system_account_id BIGINT REFERENCES system_accounts(system_account_id),
    amount_paise BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ledger_entries_nonzero CHECK (amount_paise <> 0),
    CONSTRAINT ledger_entries_one_participant CHECK (
        (wallet_id IS NOT NULL) <> (system_account_id IS NOT NULL)
    )
);
CREATE INDEX ledger_entries_transaction_idx ON ledger_entries(transaction_id);
CREATE INDEX ledger_entries_wallet_idx ON ledger_entries(wallet_id, ledger_entry_id DESC);
CREATE INDEX ledger_entries_recipient_transfer_idx
    ON ledger_entries(wallet_id, transaction_id)
    WHERE wallet_id IS NOT NULL AND amount_paise > 0;
CREATE INDEX ledger_entries_wallet_created_id_idx
    ON ledger_entries(wallet_id, created_at DESC, ledger_entry_id DESC)
    INCLUDE (transaction_id, amount_paise);
CREATE INDEX ledger_entries_system_idx ON ledger_entries(system_account_id);
CREATE UNIQUE INDEX ledger_entries_transaction_wallet_unique
    ON ledger_entries(transaction_id, wallet_id) WHERE wallet_id IS NOT NULL;
CREATE UNIQUE INDEX ledger_entries_transaction_system_unique
    ON ledger_entries(transaction_id, system_account_id) WHERE system_account_id IS NOT NULL;

CREATE TABLE transaction_status_history (
    status_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT NOT NULL REFERENCES transactions(transaction_id),
    status transaction_status NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX transaction_status_history_transaction_idx
    ON transaction_status_history(transaction_id, status_history_id);

CREATE TABLE idempotency_keys (
    idempotency_key_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    key UUID NOT NULL,
    request_hash BYTEA NOT NULL,
    status idempotency_status NOT NULL DEFAULT 'IN_PROGRESS',
    response_code SMALLINT,
    response_body TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT idempotency_keys_user_key_unique UNIQUE (user_id, key),
    CONSTRAINT idempotency_keys_hash_sha256 CHECK (octet_length(request_hash) = 32),
    CONSTRAINT idempotency_keys_response_code_range CHECK (response_code BETWEEN 100 AND 599),
    CONSTRAINT idempotency_keys_response_state CHECK (
        (status = 'IN_PROGRESS' AND response_code IS NULL AND response_body IS NULL)
        OR (status = 'COMPLETED' AND response_code IS NOT NULL AND response_body IS NOT NULL)
    )
);

-- History is append-only. Corrections are new reversing transactions.
CREATE FUNCTION reject_history_change() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Rows in % cannot be updated or deleted', TG_TABLE_NAME USING ERRCODE = '23514';
END;
$$;
CREATE TRIGGER status_history_immutable BEFORE UPDATE OR DELETE ON transaction_status_history
FOR EACH ROW EXECUTE FUNCTION reject_history_change();
CREATE TRIGGER accounts_immutable BEFORE UPDATE OR DELETE ON accounts
FOR EACH ROW EXECUTE FUNCTION reject_history_change();
CREATE TRIGGER system_accounts_immutable BEFORE UPDATE OR DELETE ON system_accounts
FOR EACH ROW EXECUTE FUNCTION reject_history_change();

CREATE FUNCTION guard_ledger_entries() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE parent_status transaction_status;
BEGIN
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION 'Ledger entries are immutable; create a reversal' USING ERRCODE = '23514';
    END IF;
    SELECT transaction_status INTO parent_status FROM transactions
    WHERE transaction_id = NEW.transaction_id FOR UPDATE;
    IF FOUND AND parent_status <> 'PENDING' THEN
        RAISE EXCEPTION 'Entries can only be inserted into pending transactions' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER ledger_entries_guard BEFORE INSERT OR UPDATE OR DELETE ON ledger_entries
FOR EACH ROW EXECUTE FUNCTION guard_ledger_entries();

CREATE FUNCTION guard_transaction_history() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Transaction history cannot be deleted' USING ERRCODE = '23514';
    END IF;
    IF OLD.transaction_status IN ('POSTED', 'FAILED') THEN
        RAISE EXCEPTION 'Completed transaction history is immutable' USING ERRCODE = '23514';
    END IF;
    IF (NEW.transaction_id, NEW.transaction_type, NEW.transaction_amount_paise, NEW.transaction_date,
        NEW.wallet_id, NEW.initiated_by_user_id, NEW.account_id, NEW.reversal_of_transaction_id) IS DISTINCT FROM
       (OLD.transaction_id, OLD.transaction_type, OLD.transaction_amount_paise, OLD.transaction_date,
        OLD.wallet_id, OLD.initiated_by_user_id, OLD.account_id, OLD.reversal_of_transaction_id) THEN
        RAISE EXCEPTION 'Transaction terms cannot be changed' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER transactions_guard BEFORE UPDATE OR DELETE ON transactions
FOR EACH ROW EXECUTE FUNCTION guard_transaction_history();

CREATE FUNCTION guard_idempotency_history() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Idempotency history cannot be deleted' USING ERRCODE = '23514';
    END IF;
    IF OLD.status = 'COMPLETED' THEN
        RAISE EXCEPTION 'A completed response cannot be changed' USING ERRCODE = '23514';
    END IF;
    IF (NEW.idempotency_key_id, NEW.user_id, NEW.key, NEW.request_hash, NEW.created_at) IS DISTINCT FROM
       (OLD.idempotency_key_id, OLD.user_id, OLD.key, OLD.request_hash, OLD.created_at) THEN
        RAISE EXCEPTION 'An idempotency request cannot be changed' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER idempotency_keys_guard BEFORE UPDATE OR DELETE ON idempotency_keys
FOR EACH ROW EXECUTE FUNCTION guard_idempotency_history();

-- Each job's row is locked for the whole run; the job never updates this row.
CREATE TABLE job_locks (
    job_name VARCHAR(100) PRIMARY KEY
);
INSERT INTO job_locks(job_name) VALUES ('ledger_reconciliation');

CREATE TABLE reconciliation_runs (
    run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- No FK to job_locks: separate audit transactions must not wait on the job's own FOR UPDATE lock.
    job_name VARCHAR(100) NOT NULL,
    started_at TIMESTAMPTZ DEFAULT clock_timestamp(),
    finished_at TIMESTAMPTZ,
    status VARCHAR(20) NOT NULL DEFAULT 'RUNNING',
    checks_completed SMALLINT NOT NULL DEFAULT 0 CHECK (checks_completed BETWEEN 0 AND 5),
    problem_count BIGINT NOT NULL DEFAULT 0 CHECK (problem_count >= 0),
    error_message TEXT,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    requested_by_user_id BIGINT REFERENCES users(user_id),
    CONSTRAINT reconciliation_runs_status CHECK (status IN ('QUEUED', 'RUNNING', 'PASSED', 'ISSUES_FOUND', 'FAILED')),
    CONSTRAINT reconciliation_runs_finished CHECK (
        (status IN ('QUEUED', 'RUNNING') AND finished_at IS NULL)
        OR (status NOT IN ('QUEUED', 'RUNNING') AND finished_at IS NOT NULL)
    ),
    CONSTRAINT reconciliation_runs_started CHECK (
        (status = 'QUEUED' AND started_at IS NULL)
        OR (status <> 'QUEUED' AND started_at IS NOT NULL)
    ),
    CONSTRAINT reconciliation_runs_result CHECK (
        status NOT IN ('PASSED', 'ISSUES_FOUND')
        OR (checks_completed = 5 AND (
            (status = 'PASSED' AND problem_count = 0)
            OR (status = 'ISSUES_FOUND' AND problem_count > 0)
        ))
    ),
    CONSTRAINT reconciliation_runs_failure CHECK ((status = 'FAILED') = (error_message IS NOT NULL))
);
CREATE INDEX reconciliation_runs_job_started_idx ON reconciliation_runs(job_name, started_at DESC);
CREATE INDEX reconciliation_runs_queued_idx ON reconciliation_runs(requested_at, run_id)
    WHERE status = 'QUEUED';

CREATE TABLE reconciliation_problems (
    problem_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES reconciliation_runs(run_id),
    check_name VARCHAR(40) NOT NULL,
    -- Text allows GLOBAL as well as wallet, transaction, and entry IDs; no FK to possibly missing entities.
    entity_id VARCHAR(100) NOT NULL,
    expected_value TEXT NOT NULL,
    actual_value TEXT NOT NULL,
    CONSTRAINT reconciliation_problems_check CHECK (check_name IN (
        'GLOBAL_LEDGER_BALANCE', 'TRANSFER_BALANCE', 'WALLET_BALANCE',
        'OVERDRAFT', 'TRANSFER_WITHOUT_ENTRIES', 'ENTRY_WITHOUT_TRANSFER'
    )),
    CONSTRAINT reconciliation_problems_run_check_entity_unique UNIQUE (run_id, check_name, entity_id)
);

-- Held intents are not ledger entries and do not reserve or move money.
CREATE TABLE transfer_holds (
    transaction_id BIGINT PRIMARY KEY REFERENCES transactions(transaction_id),
    rule_code VARCHAR(100) NOT NULL,
    reason TEXT NOT NULL,
    held_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    released_by BIGINT REFERENCES users(user_id),
    released_at TIMESTAMPTZ,
    CONSTRAINT transfer_holds_release_audit CHECK ((released_by IS NULL) = (released_at IS NULL))
);

CREATE TABLE held_transfer_recipients (
    transaction_id BIGINT NOT NULL REFERENCES transfer_holds(transaction_id),
    wallet_id BIGINT NOT NULL REFERENCES wallets(wallet_id),
    amount_paise BIGINT NOT NULL CHECK (amount_paise > 0),
    PRIMARY KEY (transaction_id, wallet_id)
);
CREATE TRIGGER held_recipients_immutable BEFORE UPDATE OR DELETE ON held_transfer_recipients
FOR EACH ROW EXECUTE FUNCTION reject_history_change();

CREATE FUNCTION guard_transfer_hold_audit() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Hold audit cannot be deleted' USING ERRCODE = '23514';
    END IF;
    IF (NEW.transaction_id, NEW.rule_code, NEW.reason, NEW.held_at) IS DISTINCT FROM
       (OLD.transaction_id, OLD.rule_code, OLD.reason, OLD.held_at)
       OR OLD.released_at IS NOT NULL OR NEW.released_at IS NULL OR NEW.released_by IS NULL THEN
        RAISE EXCEPTION 'Only a first release may update a hold audit' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER transfer_holds_audit_guard BEFORE UPDATE OR DELETE ON transfer_holds
FOR EACH ROW EXECUTE FUNCTION guard_transfer_hold_audit();

CREATE FUNCTION guard_held_transfer_state() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.transaction_status = 'HELD' AND
       (OLD.transaction_status <> 'PENDING' OR NEW.transaction_type <> 'TRANSFER' OR EXISTS (
           SELECT 1 FROM ledger_entries WHERE transaction_id = NEW.transaction_id
       )) THEN
        RAISE EXCEPTION 'Only an unposted transfer without ledger entries may be held' USING ERRCODE = '23514';
    END IF;
    IF OLD.transaction_status = 'HELD' AND NEW.transaction_status NOT IN ('PENDING', 'FAILED') THEN
        RAISE EXCEPTION 'A held transfer must be released or cancelled' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER held_transfer_state_guard BEFORE UPDATE ON transactions
FOR EACH ROW EXECUTE FUNCTION guard_held_transfer_state();

-- All tunable rule thresholds and rolling windows live in the database.
CREATE TABLE risk_rules (
    rule_code VARCHAR(100) PRIMARY KEY,
    rule_name VARCHAR(100) NOT NULL,
    lookback_minutes INTEGER CHECK (lookback_minutes > 0),
    threshold NUMERIC(30, 10) NOT NULL CHECK (threshold > 0 AND threshold <> 'NaN'::NUMERIC),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT risk_rules_rule_name_key UNIQUE (rule_name),
    CONSTRAINT risk_rules_whole_threshold CHECK (
        rule_code NOT IN ('TRANSFER_VELOCITY_EXCEEDED', 'FIRST_TIME_RECIPIENT_HIGH_AMOUNT')
        OR (threshold = trunc(threshold) AND threshold <= 9223372036854775807)
    ),
    CONSTRAINT risk_rules_lookback_scope CHECK (
        (rule_code = 'FIRST_TIME_RECIPIENT_HIGH_AMOUNT' AND lookback_minutes IS NULL)
        OR (rule_code <> 'FIRST_TIME_RECIPIENT_HIGH_AMOUNT' AND lookback_minutes IS NOT NULL)
    )
);

-- Threshold means count, multiplier, or per-recipient paise respectively.
INSERT INTO risk_rules (rule_code, rule_name, lookback_minutes, threshold) VALUES
    ('TRANSFER_VELOCITY_EXCEEDED', 'Velocity', 10, 5),
    ('HISTORICAL_AVERAGE_EXCEEDED', 'Amount Spike', 30 * 24 * 60, 5),
    ('FIRST_TIME_RECIPIENT_HIGH_AMOUNT', 'NewPayeeLargeAmount', NULL, 10000 * 100);

CREATE TABLE transfer_flags (
    transaction_id BIGINT PRIMARY KEY REFERENCES transactions(transaction_id),
    rule_code VARCHAR(100) NOT NULL,
    reason TEXT NOT NULL,
    flagged_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
-- Advisory assessment for the rule that returned HOLD or FLAG; it never approves a transfer.
CREATE TABLE risk_flags (
    transaction_id BIGINT PRIMARY KEY REFERENCES transactions(transaction_id),
    rule_code VARCHAR(100) NOT NULL,
    rule_name VARCHAR(100) NOT NULL,
    rule_action VARCHAR(10) NOT NULL CHECK (rule_action IN ('HOLD', 'FLAG')),
    reason TEXT NOT NULL,
    label VARCHAR(20) NOT NULL CHECK (label IN ('likely_ok', 'review', 'likely_fraud')),
    explanation TEXT NOT NULL CHECK (char_length(btrim(explanation)) BETWEEN 1 AND 2000),
    assessment_source VARCHAR(10) NOT NULL CHECK (assessment_source IN ('LLM', 'FALLBACK')),
    flagged_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    flagged_date DATE GENERATED ALWAYS AS ((flagged_at AT TIME ZONE 'UTC')::DATE) STORED
);
CREATE INDEX risk_flags_rule_date_idx ON risk_flags(rule_name, flagged_date DESC, flagged_at DESC);
CREATE TRIGGER risk_flags_immutable BEFORE UPDATE OR DELETE ON risk_flags
FOR EACH ROW EXECUTE FUNCTION reject_history_change();
